#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const referencePath = path.join(
  __dirname,
  '..',
  'references',
  'skill-frontmatter-capabilities.generated.md',
);

function fail(message) {
  process.stderr.write(`[ERROR] ${message}\n`);
  process.exit(1);
}

function usage() {
  process.stdout.write(`Usage:
  node generate_skill_frontmatter_reference.mjs [--check|--write] [--repo-root <path>]

Options:
  --check  Fail if the committed generated reference differs from the registry.
  --write  Replace the committed generated reference.
  --repo-root <path>  Agent-workflows repository root. Default: current directory.
  -h, --help  Show this help message.

With no option, the generated Markdown is written to stdout.
`);
}

function markdownCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function renderReference(registry) {
  const lines = [
    '# Skill Frontmatter Capability Reference',
    '',
    '<!-- Generated by scripts/generate_skill_frontmatter_reference.mjs. Do not edit by hand. -->',
    '',
    `Registry schema: ${registry.schemaVersion}. Verified: ${registry.verifiedOn}.`,
    '',
    `Required semantics: ${registry.requiredSemantics}.`,
    '',
    '## Profiles',
    '',
    '| Profile | Platform | Target version | Description |',
    '| --- | --- | --- | --- |',
  ];
  for (const [name, profile] of Object.entries(registry.profiles)) {
    lines.push(`| \`${markdownCell(name)}\` | ${markdownCell(profile.platform)} | ${markdownCell(profile.targetVersion ?? 'n/a')} | ${markdownCell(profile.description)} |`);
  }
  lines.push(
    '',
    '## Fields',
    '',
    '| Field | Owner | Required | Type | Profiles | Accepted values | Value matching | Version evidence | Requires |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  );
  for (const [name, field] of Object.entries(registry.fields)) {
    const types = field.typeByProfile
      ? `${field.type}; ${Object.entries(field.typeByProfile).map(([profile, type]) => `${profile}=${type}`).join(', ')}`
      : field.type;
    const acceptedValues = field.acceptedValuesByProfile
      ? Object.entries(field.acceptedValuesByProfile)
        .map(([profile, values]) => `${profile}=${values.join('/')}`)
        .join('; ')
      : field.acceptedValues?.join('/') ?? 'any';
    const valueMatching = field.acceptedValuesByProfile
      ? Object.keys(field.acceptedValuesByProfile)
        .map((profile) => {
          const caseInsensitive = field.acceptedValuesCaseInsensitiveByProfile?.[profile]
            ?? field.acceptedValuesCaseInsensitive
            ?? false;
          return `${profile}=${caseInsensitive ? 'case-insensitive' : 'exact'}`;
        })
        .join(', ')
      : field.acceptedValues
        ? field.acceptedValuesCaseInsensitive === true ? 'case-insensitive' : 'exact'
        : 'n/a';
    const version = field.introducedVersion
      ? `introduced ${field.introducedVersion}`
      : field.verifiedAtVersion
        ? `verified ${field.verifiedAtVersion}`
        : 'n/a';
    const requires = field.requires
      ? Object.entries(field.requires).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join(', ')
      : 'none';
    lines.push(`| \`${markdownCell(name)}\` | ${markdownCell(field.owner)} | ${field.required === true ? 'yes' : 'no'} | ${markdownCell(types)} | ${markdownCell(field.profiles.join(', '))} | ${markdownCell(acceptedValues)} | ${markdownCell(valueMatching)} | ${markdownCell(version)} | ${markdownCell(requires)} |`);
  }
  lines.push(
    '',
    '## Sources',
    '',
    `- Agent Skills: ${registry.sources.agentSkills}`,
    `- Claude current: ${registry.sources.claudeCurrent}`,
    `- Claude minimum: ${registry.sources.claudeMinimum}`,
  );
  return `${lines.join('\n')}\n`;
}

const args = process.argv.slice(2);
if (args.includes('-h') || args.includes('--help')) {
  usage();
  process.exit(0);
}
let option;
let repoRoot = process.cwd();
for (let index = 0; index < args.length; index += 1) {
  const arg = args[index];
  if (arg === '--check' || arg === '--write') {
    if (option) fail('Use only one of --check or --write.');
    option = arg;
  } else if (arg === '--repo-root') {
    const value = args[++index];
    if (!value || value.startsWith('--')) fail('--repo-root requires a value.');
    repoRoot = path.resolve(value);
  } else {
    fail(`Unknown option: ${arg}`);
  }
}
const registryPath = path.join(
  repoRoot,
  'packages',
  'cli',
  'src',
  'utils',
  'skill-frontmatter-capabilities.json',
);
if (!fs.existsSync(registryPath)) fail(`Registry not found: ${registryPath}`);

const registry = JSON.parse(fs.readFileSync(registryPath, 'utf8'));
const rendered = renderReference(registry);
if (option === '--check') {
  if (!fs.existsSync(referencePath) || fs.readFileSync(referencePath, 'utf8') !== rendered) {
    fail('Generated Skill frontmatter reference is stale. Run this script with --write.');
  }
  process.stdout.write('[PASS] Skill frontmatter reference matches the registry.\n');
} else if (option === '--write') {
  fs.writeFileSync(referencePath, rendered, 'utf8');
  process.stdout.write(`${referencePath}\n`);
} else {
  process.stdout.write(rendered);
}
